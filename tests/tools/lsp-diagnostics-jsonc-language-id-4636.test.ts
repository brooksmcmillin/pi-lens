/**
 * #4636: a JSONC-by-convention file is `.json` by extension and JSONC by
 * format, so the extension-only classifier announced `json` on `didOpen` and
 * the JSON language server applied its comments-not-allowed mode
 * (`vscode-langservers-extracted` 4.10.0,
 * `lib/json-language-server/jsonServer.js:521`: `languageId === 'jsonc'` is
 * what selects `comments: 'ignore'`). Every upstream-authored comment in a
 * `tsconfig*.json` then arrived as a blocking finding.
 *
 * The case drives the REAL `lsp_diagnostics` handler, LSPService, and client
 * to a stdio JSON-RPC wire, and reads the announced `languageId` from a trace
 * the fake server writes when it RECEIVES `didOpen`. Only the server binary
 * (the shared fixture) and the project's server registration are doubles: the
 * classifier, the touch path and the notify queue are production code.
 *
 * Screens: **all-mocks** — the spellings under test come from the registry and
 * the wire; **wrong-layer pin** — the assertion is the frame the server
 * received, not the helper's return value; **loose bound** — a plain
 * `data.json` in the same call must stay `json`, so a fix that announced
 * `jsonc` for every JSON file could not pass.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import {
	resetProjectTrust,
	setProjectTrustState,
} from "../../clients/project-trust.js";
import {
	cleanupTestEnvironmentsDrained,
	setupTestEnvironment,
} from "../clients/test-utils.js";

const fakeServer = fileURLToPath(
	new URL("../fixtures/fake-lsp-server.mjs", import.meta.url),
);
const env = setupTestEnvironment("pi-lens-4636-jsonc-");
const workspace = env.tmpDir;
const trace = path.join(workspace, "server.trace");

let service: { shutdown: () => Promise<void> } | undefined;

/** The `languageId` the server received for `file`, from its own trace. */
function announcedLanguageOf(file: string): string | undefined {
	if (!fs.existsSync(trace)) return undefined;
	const uri = pathToFileURL(file).href;
	const line = fs
		.readFileSync(trace, "utf8")
		.split("\n")
		.find((entry) => entry.startsWith(`language ${uri} `));
	return line?.slice(`language ${uri} `.length);
}

async function diagnose(files: readonly string[]): Promise<string> {
	const { createLspDiagnosticsTool } =
		await import("../../tools/lsp-diagnostics.js");
	const result = (await createLspDiagnosticsTool().execute(
		"probe-4636",
		{ paths: [...files], serverScope: "primary", waitMs: 3000, concurrency: 1 },
		undefined,
		null,
		{ cwd: workspace },
	)) as { content: Array<{ text?: string }> };
	return String(result.content[0]?.text);
}

beforeAll(async () => {
	// Host-boundary stub: a project-configured server needs pi's trust (#4248).
	setProjectTrustState("trusted");
	const shim = path.join(workspace, "json-probe-server.mjs");
	fs.writeFileSync(
		shim,
		[
			`process.env.FAKE_LSP_TRACE_FILE = ${JSON.stringify(trace)};`,
			'process.env.FAKE_LSP_TRACE_LANGUAGE_ID = "1";',
			`import(${JSON.stringify(pathToFileURL(fakeServer).href)});`,
			"",
		].join("\n"),
	);
	fs.writeFileSync(
		path.join(workspace, "package.json"),
		'{"name":"jsonc-probe","version":"0.0.0"}\n',
	);
	fs.mkdirSync(path.join(workspace, ".pi-lens"), { recursive: true });
	fs.writeFileSync(
		path.join(workspace, ".pi-lens", "lsp.json"),
		JSON.stringify({
			servers: {
				"json-probe": {
					name: "JSON probe server",
					extensions: [".json"],
					command: process.execPath,
					args: [shim],
					rootMarkers: ["package.json"],
				},
			},
			disabledServers: [
				"json",
				"typescript",
				"deno",
				"go",
				"opengrep",
				"ast-grep",
				"typos",
			],
		}),
	);
	const config = await import("../../clients/lsp/config.js");
	await config.initLSPConfig(workspace);
	const lsp = await import("../../clients/lsp/index.js");
	service = lsp.getLSPService();
});

afterAll(async () => {
	await cleanupTestEnvironmentsDrained("pi-lens-4636-jsonc-", {
		beforeDrain: async () => {
			await service?.shutdown();
		},
	});
	resetProjectTrust();
});

describe("a JSONC-by-convention config file (#4636)", () => {
	it("announces jsonc for the tsconfig/jsconfig family and json for every other .json", async () => {
		// The Vite template's file, comments included: `tsc --noEmit` is green
		// on it, so only the format's own server has anything to say.
		const tsconfigApp = path.join(workspace, "tsconfig.app.json");
		fs.writeFileSync(
			tsconfigApp,
			'{\n  // generated by the Vite template\n  "compilerOptions": {}\n}\n',
		);
		const tsconfig = path.join(workspace, "tsconfig.json");
		fs.writeFileSync(tsconfig, '{ "files": [], "references": [] }\n');
		const jsconfigBase = path.join(workspace, "jsconfig.base.json");
		fs.writeFileSync(jsconfigBase, "{}\n");
		const plainJson = path.join(workspace, "data.json");
		fs.writeFileSync(plainJson, '{ "comments": false }\n');

		await diagnose([tsconfigApp, tsconfig, jsconfigBase, plainJson]);

		expect(announcedLanguageOf(tsconfigApp)).toBe("jsonc");
		expect(announcedLanguageOf(tsconfig)).toBe("jsonc");
		expect(announcedLanguageOf(jsconfigBase)).toBe("jsonc");
		// The bound: everything else keeps the extension's answer.
		expect(announcedLanguageOf(plainJson)).toBe("json");
	}, 60_000);
});
